export const getMedicationsByStatus = (status = "All") => {
  if (status === "All") return initialMedications;
  return initialMedications.filter((m) => m.status === status);
};

export const getActiveMedications = () =>
  initialMedications.filter((m) => m.status === "Active");

export const getCompletedMedications = () =>
  initialMedications.filter((m) => m.status === "Completed");

export const getRefillNeededMedications = () =>
  initialMedications.filter((m) => m.status === "Refill Needed");

export const getDiscontinuedMedications = () =>
  initialMedications.filter((m) => m.status === "Discontinued");

export const getMedicationById = (id) =>
  initialMedications.find((m) => m.id === id);

export const getMedicationsByPatient = (patientId) =>
  initialMedications.filter((m) => m.patientId === patientId);

export const getMedicationsByDepartment = (department) =>
  initialMedications.filter((m) => m.department === department);

export const getMedicationsByDoctor = (doctor) =>
  initialMedications.filter((m) => m.doctor === doctor);

export const getMedicationsByRoute = (route) =>
  initialMedications.filter((m) => m.route === route);

export const getStatusCounts = () => ({
  All: initialMedications.length,
  Active: initialMedications.filter((m) => m.status === "Active").length,
  "Refill Needed": initialMedications.filter((m) => m.status === "Refill Needed").length,
  Completed: initialMedications.filter((m) => m.status === "Completed").length,
  Discontinued: initialMedications.filter((m) => m.status === "Discontinued").length,
});

export const getUniqueRoutes = () => [
  ...new Set(initialMedications.map((m) => m.route)),
];

export const getUniquePharmacies = () => [
  ...new Set(initialMedications.map((m) => m.pharmacy)),
];

export const getDepartmentCounts = () => {
  const counts = {};
  initialMedications.forEach((m) => {
    counts[m.department] = (counts[m.department] || 0) + 1;
  });
  return counts;
};

export const searchMedications = (query) => {
  if (!query) return initialMedications;
  const q = query.toLowerCase();
  return initialMedications.filter(
    (m) =>
      m.patient.toLowerCase().includes(q) ||
      m.medicine.toLowerCase().includes(q) ||
      m.genericName.toLowerCase().includes(q) ||
      m.doctor.toLowerCase().includes(q) ||
      m.rxNumber.toLowerCase().includes(q) ||
      m.department.toLowerCase().includes(q)
  );
};

